-- Booking platform schema (PostgreSQL 18). Applied once by booking_platform.db.migrate().
-- Store-level FR-10: see .docs/planning-artifacts/prds/prd-booking-platform-2026-10-29/addendum.md, section A.

-- The platform's clock: the data store's clock plus a test offset (tests control the clock, NFR-11).
CREATE TABLE clock (only_row boolean PRIMARY KEY DEFAULT true CHECK (only_row), off interval NOT NULL DEFAULT '0');
INSERT INTO clock DEFAULT VALUES;
CREATE FUNCTION app_now() RETURNS timestamptz LANGUAGE sql VOLATILE AS $$
  SELECT clock_timestamp() + (SELECT off FROM clock) $$;

CREATE TABLE saunas (
  id int PRIMARY KEY, name text NOT NULL,
  capacity int NOT NULL CHECK (capacity > 0), fill_order int NOT NULL UNIQUE,
  bookable_whole boolean NOT NULL DEFAULT true);
CREATE TABLE windows (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, during tstzrange NOT NULL,
  CONSTRAINT windows_never_overlap EXCLUDE USING gist (during WITH &&),
  seat_capacity int NOT NULL DEFAULT 0 CHECK (seat_capacity >= 0),
  booked int NOT NULL DEFAULT 0,
  held int NOT NULL DEFAULT 0 CHECK (held >= 0),
  CONSTRAINT booked_within_capacity CHECK (booked >= 0 AND booked + held <= seat_capacity));
CREATE TABLE bookings (
  id bigserial PRIMARY KEY, window_id int NOT NULL REFERENCES windows(id),
  seats int NOT NULL CHECK (seats > 0),
  guest text NOT NULL DEFAULT '', created_at timestamptz NOT NULL DEFAULT app_now());
CREATE TABLE whole_bookings (
  id bigserial PRIMARY KEY, window_id int NOT NULL REFERENCES windows(id),
  sauna_id int NOT NULL REFERENCES saunas(id), UNIQUE (window_id, sauna_id));
CREATE TABLE blocks (
  id bigserial PRIMARY KEY, sauna_id int NOT NULL REFERENCES saunas(id),
  during tstzrange NOT NULL CHECK (NOT isempty(during)));

CREATE TABLE holds (
  id bigserial PRIMARY KEY, window_id int NOT NULL REFERENCES windows(id),
  seats int NOT NULL CHECK (seats > 0), session_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT app_now(),
  UNIQUE (session_id, window_id),
  expires_at timestamptz NOT NULL,
  CONSTRAINT hold_at_most_10_min CHECK (expires_at > created_at AND expires_at <= created_at + interval '10 minutes'));

-- Seat capacity = sum of Capacity of the Saunas that are neither Whole-sauna booked nor Blocked.
CREATE TABLE settings (
  only_row boolean PRIMARY KEY DEFAULT true CHECK (only_row),
  release_on boolean NOT NULL DEFAULT true, release_time time NOT NULL DEFAULT '06:00',
  booking_deadline_minutes int NOT NULL DEFAULT 5 CHECK (booking_deadline_minutes <= 45),
  venue_tz text NOT NULL DEFAULT 'Europe/Oslo');
INSERT INTO settings DEFAULT VALUES;
-- A Sauna marked Whole-booking-only in a Window (FR-41).
CREATE TABLE marks (
  id bigserial PRIMARY KEY, window_id int NOT NULL REFERENCES windows(id),
  sauna_id int NOT NULL REFERENCES saunas(id), UNIQUE (window_id, sauna_id));
-- A recognised release. Kept apart from marks so that no recompute ever locks a mark row
-- (that would invert the lock order against a statement that deletes a mark).
CREATE TABLE releases (
  window_id int NOT NULL, sauna_id int NOT NULL, released_at timestamptz NOT NULL,
  PRIMARY KEY (window_id, sauna_id));

-- The Release time of a Window: a clock time on the date the Window starts, in Venue time.
CREATE FUNCTION release_due(wid int) RETURNS timestamptz LANGUAGE sql STABLE AS $$
  SELECT ((lower(w.during) AT TIME ZONE st.venue_tz)::date + st.release_time) AT TIME ZONE st.venue_tz
  FROM windows w, settings st WHERE w.id = wid
$$;
-- Marked and not released. The release is a condition checked against the clock (NFR-11).
CREATE FUNCTION mark_closed(wid int, sid int) RETURNS boolean LANGUAGE sql VOLATILE AS $$
  SELECT EXISTS (SELECT 1 FROM marks m WHERE m.window_id = wid AND m.sauna_id = sid)
     AND NOT EXISTS (SELECT 1 FROM releases r WHERE r.window_id = wid AND r.sauna_id = sid)
     AND NOT COALESCE((SELECT release_on AND app_now() >= release_due(wid) FROM settings), false)
$$;
CREATE FUNCTION sauna_open_for_seats(wid int, sid int) RETURNS boolean LANGUAGE sql VOLATILE AS $$
  SELECT NOT EXISTS (SELECT 1 FROM whole_bookings wb WHERE wb.window_id = wid AND wb.sauna_id = sid)
     AND NOT EXISTS (SELECT 1 FROM blocks b, windows w WHERE w.id = wid AND b.sauna_id = sid AND b.during && w.during)
     AND NOT mark_closed(wid, sid)
$$;
-- Seat capacity = sum of Capacity of the Saunas open for Seats (not Whole-sauna booked, Blocked or marked and unreleased).
CREATE FUNCTION window_open_capacity(wid int) RETURNS int LANGUAGE sql VOLATILE AS $$
  SELECT COALESCE(SUM(s.capacity), 0)::int FROM saunas s, windows w
  WHERE w.id = wid AND sauna_open_for_seats(w.id, s.id)
$$;
-- Room ahead of a Sauna: the Capacity of the Saunas before it in the Fill order that are open for Seats.
CREATE FUNCTION room_ahead(wid int, sid int) RETURNS int LANGUAGE sql VOLATILE AS $$
  SELECT COALESCE(SUM(s2.capacity), 0)::int FROM saunas s1 JOIN saunas s2 ON s2.fill_order < s1.fill_order
  WHERE s1.id = sid AND sauna_open_for_seats(wid, s2.id)
$$;
CREATE FUNCTION window_booked_seats(wid int) RETURNS int LANGUAGE sql STABLE AS $$
  SELECT COALESCE(SUM(seats), 0)::int FROM bookings WHERE window_id = wid
$$;
-- Held Seats count only while the Hold has not expired, whether or not any cleanup has run.
CREATE FUNCTION window_held_seats(wid int) RETURNS int LANGUAGE sql VOLATILE AS $$
  SELECT COALESCE(SUM(seats), 0)::int FROM holds WHERE window_id = wid AND expires_at > app_now()
$$;
-- What a Guest is shown: computed from the rows, never from the stored counter.
CREATE FUNCTION seats_left(wid int) RETURNS int LANGUAGE sql VOLATILE AS $$
  SELECT window_open_capacity(w.id) - window_booked_seats(w.id)
         - (SELECT COALESCE(SUM(seats), 0)::int FROM holds h WHERE h.window_id = w.id AND h.expires_at > app_now())
  FROM windows w WHERE w.id = wid
$$;

-- Lock the Window row FIRST (a new statement then sees everything committed before the lock
-- was granted), then re-derive both numbers from the source rows. The CHECK does the refusing.
CREATE FUNCTION recompute_window(wid int) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  PERFORM 1 FROM windows WHERE id = wid FOR UPDATE;
  INSERT INTO releases (window_id, sauna_id, released_at) SELECT m.window_id, m.sauna_id, app_now() FROM marks m WHERE m.window_id = wid AND (SELECT release_on FROM settings) AND app_now() >= release_due(wid) AND NOT EXISTS (SELECT 1 FROM whole_bookings wb WHERE wb.window_id = m.window_id AND wb.sauna_id = m.sauna_id) ON CONFLICT DO NOTHING;
  UPDATE windows SET seat_capacity = window_open_capacity(wid),
                     booked = window_booked_seats(wid),
                     held = window_held_seats(wid)
  WHERE id = wid;
END $$;

CREATE FUNCTION lock_windows(ids int[]) RETURNS void LANGUAGE plpgsql AS $$
DECLARE w int;
BEGIN
  FOR w IN SELECT DISTINCT x FROM unnest(ids) AS x WHERE x IS NOT NULL ORDER BY x LOOP
    PERFORM 1 FROM windows WHERE id = w FOR UPDATE;
  END LOOP;
END $$;

CREATE FUNCTION trg_lock_win() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM lock_windows(ARRAY[CASE WHEN TG_OP <> 'INSERT' THEN OLD.window_id END,
                             CASE WHEN TG_OP <> 'DELETE' THEN NEW.window_id END]);
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;

CREATE FUNCTION trg_lock_blocks() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE r1 tstzrange; r2 tstzrange; w int;
BEGIN
  IF TG_OP IN ('UPDATE','DELETE') THEN r1 := OLD.during; END IF;
  IF TG_OP IN ('INSERT','UPDATE') THEN r2 := NEW.during; END IF;
  FOR w IN SELECT id FROM windows WHERE (r1 && during) OR (r2 && during) ORDER BY id LOOP
    PERFORM 1 FROM windows WHERE id = w FOR UPDATE;
  END LOOP;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;

CREATE FUNCTION trg_bookings() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE a int; b int; w int;
BEGIN
  IF TG_OP IN ('UPDATE','DELETE') THEN a := OLD.window_id; END IF;
  IF TG_OP IN ('INSERT','UPDATE') THEN b := NEW.window_id; END IF;
  FOR w IN SELECT DISTINCT x FROM unnest(ARRAY[a, b]) AS x WHERE x IS NOT NULL ORDER BY x LOOP
    PERFORM recompute_window(w);
  END LOOP;
  RETURN NULL;
END $$;

CREATE FUNCTION trg_whole() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE a int; b int; w int;
BEGIN
  IF TG_OP IN ('UPDATE','DELETE') THEN a := OLD.window_id; END IF;
  IF TG_OP IN ('INSERT','UPDATE') THEN b := NEW.window_id; END IF;
  FOR w IN SELECT DISTINCT x FROM unnest(ARRAY[a, b]) AS x WHERE x IS NOT NULL ORDER BY x LOOP
    PERFORM recompute_window(w);
  END LOOP;
  RETURN NULL;
END $$;

-- A Block touches every Window that overlaps its period; Windows are locked in id order.
CREATE FUNCTION trg_blocks() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE r1 tstzrange; r2 tstzrange; w int;
BEGIN
  IF TG_OP IN ('UPDATE','DELETE') THEN r1 := OLD.during; END IF;
  IF TG_OP IN ('INSERT','UPDATE') THEN r2 := NEW.during; END IF;
  FOR w IN SELECT id FROM windows WHERE (r1 && during) OR (r2 && during) ORDER BY id LOOP
    PERFORM recompute_window(w);
  END LOOP;
  RETURN NULL;
END $$;

CREATE FUNCTION trg_saunas() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE w int;
BEGIN
  FOR w IN SELECT id FROM windows ORDER BY id LOOP PERFORM recompute_window(w); END LOOP;
  RETURN NULL;
END $$;

-- FR-29: a Whole-sauna booking needs a Sauna that is bookable whole and not Blocked. An open Sauna also needs
-- room ahead for every Seat booked and held, and a Window that has not started or has no Seat booking.
-- A marked, unreleased Sauna holds no Seats, so it skips the placement tests.
CREATE FUNCTION trg_check_whole() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE bk int; hd int;
BEGIN
  IF NOT (SELECT bookable_whole FROM saunas WHERE id = NEW.sauna_id) THEN
    RAISE EXCEPTION 'Sauna % cannot be booked whole', NEW.sauna_id USING ERRCODE = '23514';
  END IF;
  IF EXISTS (SELECT 1 FROM blocks b, windows w WHERE w.id = NEW.window_id AND b.sauna_id = NEW.sauna_id AND b.during && w.during) THEN
    RAISE EXCEPTION 'Sauna % is Blocked', NEW.sauna_id USING ERRCODE = '23514';
  END IF;
  IF  NOT mark_closed(NEW.window_id, NEW.sauna_id) THEN
    bk := window_booked_seats(NEW.window_id);
    hd := window_held_seats(NEW.window_id);
    IF bk + hd > room_ahead(NEW.window_id, NEW.sauna_id) THEN
      RAISE EXCEPTION 'Seats booked or held (%) would be placed in or before Sauna %', bk + hd, NEW.sauna_id USING ERRCODE = '23514';
    END IF;
    IF bk > 0 AND (SELECT lower(during) <= app_now() FROM windows WHERE id = NEW.window_id) THEN
      RAISE EXCEPTION 'Window has started and has Seat bookings' USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NULL;
END $$;

-- FR-41 / D8: a mark is refused while Seats are placed in the Sauna, held Seats included.
CREATE FUNCTION trg_check_mark() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT (SELECT bookable_whole FROM saunas WHERE id = NEW.sauna_id) THEN
    RAISE EXCEPTION 'Sauna % cannot be marked: not bookable whole', NEW.sauna_id USING ERRCODE = '23514';
  END IF;
  IF  NOT EXISTS (SELECT 1 FROM whole_bookings WHERE window_id = NEW.window_id AND sauna_id = NEW.sauna_id)
     AND NOT EXISTS (SELECT 1 FROM blocks b, windows w WHERE w.id = NEW.window_id AND b.sauna_id = NEW.sauna_id AND b.during && w.during) THEN
    IF window_booked_seats(NEW.window_id) + window_held_seats(NEW.window_id) > room_ahead(NEW.window_id, NEW.sauna_id) THEN
      RAISE EXCEPTION 'Seats are placed in Sauna % in this Window', NEW.sauna_id USING ERRCODE = '23514';
    END IF;
  END IF;
  RETURN NULL;
END $$;

CREATE FUNCTION trg_marks_cleanup() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN DELETE FROM releases WHERE window_id = OLD.window_id AND sauna_id = OLD.sauna_id; RETURN NULL; END $$;

-- A release row may only be written when the release is due (it cannot be forged early).
CREATE FUNCTION trg_check_release() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM marks WHERE window_id = NEW.window_id AND sauna_id = NEW.sauna_id)
     OR NOT (SELECT release_on FROM settings) OR app_now() < release_due(NEW.window_id) THEN
    RAISE EXCEPTION 'release of Sauna % in Window % is not due', NEW.sauna_id, NEW.window_id USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;

-- A change of the Release time first brings every release that is already due up to date, under the old setting.
CREATE FUNCTION trg_settings() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE w int;
BEGIN
  FOR w IN SELECT id FROM windows ORDER BY id LOOP PERFORM recompute_window(w); END LOOP;
  RETURN NEW;
END $$;

CREATE FUNCTION trg_windows_ins() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN PERFORM recompute_window(NEW.id); RETURN NULL; END $$;

CREATE FUNCTION verify_window() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM 1 FROM windows w WHERE w.id = NEW.id
    AND (w.seat_capacity > window_open_capacity(w.id) OR w.booked <> window_booked_seats(w.id)
         OR w.held < window_held_seats(w.id));  -- stale-high held (an expiry since the last write) is safe
  IF FOUND THEN
    RAISE EXCEPTION 'window % is out of step with its bookings, Blocks or Whole-sauna bookings', NEW.id
      USING ERRCODE = '23514';
  END IF;
  RETURN NULL;
END $$;

-- Helpers for the application rules (booking deadline, FR-39). The clock is the data store's (NFR-11).
CREATE FUNCTION booking_deadline(wid int) RETURNS timestamptz LANGUAGE sql STABLE AS $$
  SELECT lower(w.during) + make_interval(mins => st.booking_deadline_minutes) FROM windows w, settings st WHERE w.id = wid
$$;

